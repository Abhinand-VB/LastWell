// Sonic TTS for the audio robustness run: one caller/dispatcher line → raw µ-law 8 kHz (phone audio,
// what Ink sees on a real call). Cached on disk by content hash, so a re-run generates nothing new.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export interface SonicCfg {
  apiKey: string;
  version: string;
  model: string;
  baseUrl?: string;
}

export interface VoiceSpec {
  id: string;
  /** Sonic 3 generation_config: speed 0.6–1.5, emotion from Cartesia's enum. */
  speed?: number;
  emotion?: string;
}

/** µ-law 8 kHz: 8000 bytes per second. */
export const audioSeconds = (bytes: number): number => bytes / 8000;

export function requestBody(cfg: Pick<SonicCfg, "model">, text: string, v: VoiceSpec): Record<string, unknown> {
  const gen: Record<string, unknown> = {};
  if (v.speed !== undefined) gen.speed = v.speed;
  if (v.emotion !== undefined) gen.emotion = v.emotion;
  return {
    model_id: cfg.model,
    transcript: text,
    voice: { mode: "id", id: v.id },
    language: "en",
    output_format: { container: "raw", encoding: "pcm_mulaw", sample_rate: 8000 },
    ...(Object.keys(gen).length > 0 ? { generation_config: gen } : {}),
  };
}

export class SonicCache {
  /** Seconds of audio generated by Sonic in this run (cache hits are free). */
  generatedS = 0;
  constructor(
    private readonly cfg: SonicCfg,
    private readonly dir: string,
    private readonly budgetS: number,
  ) {
    mkdirSync(dir, { recursive: true });
  }

  async line(text: string, v: VoiceSpec): Promise<Buffer> {
    const body = requestBody(this.cfg, text, v);
    const key = createHash("sha256").update(JSON.stringify(body)).digest("hex").slice(0, 24);
    const file = join(this.dir, `${key}.ulaw`);
    if (existsSync(file)) return readFileSync(file);
    if (this.generatedS >= this.budgetS) throw new Error(`audio budget reached (${Math.round(this.generatedS)} s generated, cap ${this.budgetS} s)`);
    const res = await fetch(`${this.cfg.baseUrl ?? "https://api.cartesia.ai"}/tts/bytes`, {
      method: "POST",
      headers: { Authorization: `Bearer ${this.cfg.apiKey}`, "Cartesia-Version": this.cfg.version, "Content-Type": "application/json" },
      body: JSON.stringify(body),
      signal: AbortSignal.timeout(20_000),
    });
    if (!res.ok) throw new Error(`Sonic ${res.status}: ${(await res.text()).slice(0, 300)}`);
    const buf = Buffer.from(await res.arrayBuffer());
    this.generatedS += audioSeconds(buf.length);
    writeFileSync(file, buf);
    return buf;
  }
}

export interface VoiceInfo {
  id: string;
  name: string;
  description: string;
  locales: string[];
}

/** GET /voices (cursor pages). Used to pick an accented English voice. */
export async function listVoices(cfg: SonicCfg, query: Record<string, string>): Promise<VoiceInfo[]> {
  const out: VoiceInfo[] = [];
  let after: string | null = null;
  for (let page = 0; page < 5; page++) {
    const q = new URLSearchParams({ limit: "100", ...query, ...(after ? { starting_after: after } : {}) });
    const res = await fetch(`${cfg.baseUrl ?? "https://api.cartesia.ai"}/voices?${q}`, {
      headers: { Authorization: `Bearer ${cfg.apiKey}`, "Cartesia-Version": cfg.version },
      signal: AbortSignal.timeout(15_000),
    });
    if (!res.ok) throw new Error(`voices ${res.status}: ${(await res.text()).slice(0, 300)}`);
    const j = (await res.json()) as { data: Array<{ id: string; name: string; description?: string; accents?: Array<{ locale?: string }> }>; has_more?: boolean; next_page?: string | null };
    for (const v of j.data) out.push({ id: v.id, name: v.name, description: v.description ?? "", locales: (v.accents ?? []).flatMap((a) => (a.locale ? [a.locale] : [])) });
    if (!j.has_more || !j.next_page) break;
    after = j.next_page;
  }
  return out;
}

const NATIVE = /\b(american|british|english|australian|irish|scottish|canadian|us|uk)\b/i;
const NON_NATIVE = /\b(spanish|mexican|latin|latina|latino|hispanic|indian|hindi|french|german|chinese|mandarin|russian|italian|portuguese|brazilian|korean|japanese|arabic|filipino|vietnamese|polish|turkish|nigerian)\b/i;

/** First voice whose description says it speaks English with a non-native accent. */
export function pickAccentVoice(voices: readonly VoiceInfo[]): VoiceInfo | null {
  const scored = voices.filter((v) => {
    const d = `${v.name} ${v.description}`;
    return /accent/i.test(d) && NON_NATIVE.test(d) && !(NATIVE.test(d) && !NON_NATIVE.test(d));
  });
  return scored[0] ?? null;
}
