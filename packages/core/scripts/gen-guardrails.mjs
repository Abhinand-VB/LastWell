// Regenerates src/prompts/guardrails.ts from docs/guardrails/call-evidence-rules.model.md (D-44, D-46),
// the compact model-facing version of docs/guardrails/call-evidence-hard-rules.md. core does no file I/O
// at runtime, so the text is embedded; guardrails.test.ts fails when they drift.
// Run: node packages/core/scripts/gen-guardrails.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const doc = readFileSync(fileURLToPath(new URL("../../../docs/guardrails/call-evidence-rules.model.md", import.meta.url)), "utf8");

function slice(startMarker, endMarker) {
  const a = doc.indexOf(startMarker);
  const b = endMarker === null ? doc.length : doc.indexOf(endMarker, a);
  if (a < 0 || b < 0) throw new Error(`marker not found: ${startMarker} / ${endMarker}`);
  return doc.slice(a, b).trimEnd();
}

const full = doc.trimEnd();
// Fast-pass subset, used only if the full text slows the fast pass (D-46): intro + sections A and C.
const fast = [slice("# CALL-EVIDENCE RULES", "\n## A. "), slice("## A. ", "\n## B. "), slice("## C. ", "\n## D. ")].join("\n\n");

const out = `// GENERATED by scripts/gen-guardrails.mjs from docs/guardrails/call-evidence-rules.model.md — do not edit.
/** The whole compact rules file (every rule traces to the original as [Rn]). */
export const GUARDRAILS_MODEL = ${JSON.stringify(full)};

/** Intro + sections A and C only. */
export const GUARDRAILS_MODEL_AC = ${JSON.stringify(fast)};
`;
writeFileSync(fileURLToPath(new URL("../src/prompts/guardrails.ts", import.meta.url)), out);
console.log(`guardrails.ts: full ${full.length} chars, A+C ${fast.length} chars`);
