// Regenerates src/prompts/guardrails.ts from docs/guardrails/call-evidence-hard-rules.md (D-44).
// core does no file I/O at runtime, so the doc's text is embedded; guardrails.test.ts fails when they drift.
// Run: node packages/core/scripts/gen-guardrails.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const doc = readFileSync(fileURLToPath(new URL("../../../docs/guardrails/call-evidence-hard-rules.md", import.meta.url)), "utf8");

function slice(startMarker, endMarker) {
  const a = doc.indexOf(startMarker);
  const b = doc.indexOf(endMarker, a);
  if (a < 0 || b < 0) throw new Error(`marker not found: ${startMarker} / ${endMarker}`);
  return doc.slice(a, b).trimEnd();
}

const rules = slice("## A. Attribute", "\n## Minimal output");
const examples = slice("## Worked call examples", "\n## Evidence notes");
// Fast-pass subset (D-44: the full set made the fast pass slower): sections A, C and E.
const fastSections = [
  slice("## A. Attribute", "\n## B. "),
  slice("## C. Interpret", "\n## D. "),
  slice("## E. Record", "\n## F. "),
];

const out = `// GENERATED by scripts/gen-guardrails.mjs from docs/guardrails/call-evidence-hard-rules.md — do not edit.
// Sections A–F (rules 1–30) and the worked examples, byte for byte. The document's intro, its
// "Minimal output" field list and its evidence notes are deliberately not part of the prompt (D-44).
export const GUARDRAILS_RULES = ${JSON.stringify(rules)};

export const GUARDRAILS_EXAMPLES = ${JSON.stringify(examples)};

/** Fast-pass subset: sections A, C and E, each verbatim. */
export const GUARDRAILS_FAST = ${JSON.stringify(fastSections.join("\n\n"))};
`;
writeFileSync(fileURLToPath(new URL("../src/prompts/guardrails.ts", import.meta.url)), out);
console.log(`guardrails.ts: rules ${rules.length} chars, examples ${examples.length} chars`);
